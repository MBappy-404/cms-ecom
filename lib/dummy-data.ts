// Get shop by domain
export const getShopByDomain = (domain: string): Shop | undefined => {
  return shops.find(shop => shop.domain.toLowerCase() === domain.toLowerCase());
};

// Get shop by ID
export const getShopById = (id: string): Shop | undefined => {
  return shops.find(shop => shop.id === id);
};

// Get products by shop
export const getProductsByShop = (shopId: string): Product[] => {
  return products.filter(product => product.shopId === shopId);
};

// Get categories by shop
export const getCategoriesByShop = (shopId: string): Category[] => {
  return categories.filter(category => category.shopId === shopId);
};

// Get orders by shop
export const getOrdersByShop = (shopId: string): Order[] => {
  return orders.filter(order => order.shopId === shopId);
};

// Get customers by shop
export const getCustomersByShop = (shopId: string): Customer[] => {
  return customers.filter(customer => customer.shopId === shopId);
};
